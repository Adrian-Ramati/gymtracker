create index if not exists se_entry on set_entries (entry_id, idx);
create index if not exists se_user_time on set_entries (user_id, completed_at desc);

-- ── Biometría diaria (reloj vía Health Connect + check-in) ──
create table if not exists biometric_daily (
  user_id          uuid not null,
  day              date not null,
  hrv_rmssd_ms     numeric(5,1),
