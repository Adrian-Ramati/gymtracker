create table if not exists set_entries (
  id             uuid primary key,
  entry_id       uuid not null references exercise_entries(id) on delete cascade,
  session_id     uuid not null references workout_sessions(id) on delete cascade,
  user_id        uuid not null,
  idx            smallint not null,
  set_type       text not null default 'working' check (set_type in ('warmup', 'working', 'top', 'backoff', 'drop', 'myo_rep', 'rest_pause', 'failed_rep')),
  parent_set_id  uuid references set_entries(id) on delete cascade,
  load_kg        numeric(6,2) check (load_kg >= 0),
  reps           smallint check (reps between 0 and 100),
  rir            numeric(3,1) check (rir between 0 and 10),
  rpe            numeric(3,1) check (rpe between 1 and 10),
  effort_source  text check (effort_source in ('logged', 'voice', 'velocity', 'inferred', 'copied_prev', 'legacy')),
  completed      boolean not null default false,
  completed_at   timestamptz,
  rest_before_s  int check (rest_before_s >= 0),
  input_method   text check (input_method in ('prefill_confirm', 'stepper', 'keypad', 'voice', 'edit_after')),
  revision       int not null default 0,
  check (set_type <> 'warmup' or (rir is null and rpe is null)),
  check (set_type not in ('drop', 'myo_rep', 'rest_pause') or parent_set_id is not null)
