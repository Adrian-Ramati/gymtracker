-- Peak Physique · modelo de datos v2 (25-oct-2026)
-- Una fila por serie (con hora, descanso y procedencia del esfuerzo), biometría diaria e historial del IHO.
-- La app sigue funcionando igual antes de ejecutarlo; después, además, escribe cada sesión en las tablas nuevas,
-- guarda la biometría (reloj y check-in) en la nube y conserva las series planificadas de cada sesión.
--
-- Cómo aplicarlo: Supabase → SQL Editor → New query → pega este archivo → Run. Se puede ejecutar más de una vez:
-- no duplica nada. Si alguna vez la app no pudo escribir una sesión en las tablas nuevas, vuelve a ejecutarlo y
-- la migración del final rellena los huecos.

begin;

create extension if not exists pgcrypto;

-- ── Sesiones actuales: datos de la sesión que no caben en las columnas (series planificadas, check-in, tiempo) ──
alter table sessions add column if not exists meta jsonb;

-- ── Catálogo ──
alter table exercises add column if not exists kind text check (kind in ('compound_heavy', 'compound', 'isolation'));

create table if not exists exercise_muscles (
  exercise_id int  not null references exercises(id) on delete cascade,
  muscle      text not null,
  credit      numeric(3,2) not null check (credit in (1, 0.5, 0.25)),
  primary key (exercise_id, muscle)
);
create table if not exists exercise_aliases (
  alias       text primary key,
  exercise_id int not null references exercises(id) on delete cascade
);

-- ── Sesiones, ejercicios y series ──
create table if not exists workout_sessions (
  id                uuid primary key,
  user_id           uuid not null,
  local_date        date not null,
  started_at        timestamptz not null,
  ended_at          timestamptz,
