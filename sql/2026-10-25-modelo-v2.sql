  sleep_min        smallint,
  sleep_efficiency numeric(3,2),
  steps            int,
  weight_kg        numeric(5,2),
  subj_sleep       smallint check (subj_sleep between 1 and 5),
  subj_soreness    smallint check (subj_soreness between 1 and 5),
  subj_energy      smallint check (subj_energy between 1 and 5),
  sources          jsonb not null default '{}',
  updated_at       timestamptz not null default now(),
  primary key (user_id, day)
