-- ── Historial del IHO (lo guarda el informe semanal) ──
create table if not exists iho_snapshots (
  user_id       uuid not null,
  window_end    date not null,
  model_version text not null,
  score         smallint check (score between 0 and 100),
  label         text,
  risk          boolean not null default false,
  components    jsonb not null,
  computed_at   timestamptz not null default now(),
  primary key (user_id, window_end, model_version)
);

-- ── Estímulo por serie y volumen efectivo semanal (mismos umbrales que la app) ──
create or replace function stim_rir(rir numeric) returns numeric language sql immutable as $f$
  select case when rir is null then 0 when rir <= 1 then 1.00 when rir <= 2 then 0.95 when rir <= 3 then 0.85
              when rir <= 4 then 0.60 when rir <= 5 then 0.35 else 0 end
$f$;
create or replace view v_effective_sets_weekly with (security_invoker = true) as
select s.user_id, date_trunc('week', ws.local_date)::date as week_start, em.muscle,
       count(*) filter (where em.credit = 1) as raw_direct_sets,
       round(sum(em.credit * stim_rir(s.rir)), 2) as effective_sets
from set_entries s
join workout_sessions ws on ws.id = s.session_id and not ws.is_deload
join exercise_entries ee on ee.id = s.entry_id
join exercise_muscles em on em.exercise_id = ee.exercise_id
where s.completed and s.set_type <> 'warmup' and coalesce(s.effort_source, 'legacy') not in ('copied_prev', 'inferred')
group by 1, 2, 3;

-- ── Seguridad: cada usuario solo ve y escribe lo suyo ──
do $f$
declare t text;
begin
  foreach t in array array['workout_sessions', 'exercise_entries', 'set_entries', 'biometric_daily', 'iho_snapshots'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists own_rows on %I', t);
    execute format('create policy own_rows on %I for all using (user_id = auth.uid()) with check (user_id = auth.uid())', t);
  end loop;
end $f$;
alter table exercise_muscles enable row level security;
alter table exercise_aliases enable row level security;
drop policy if exists read_all on exercise_muscles;
drop policy if exists read_all on exercise_aliases;
create policy read_all on exercise_muscles for select using (true);
create policy read_all on exercise_aliases for select using (true);

